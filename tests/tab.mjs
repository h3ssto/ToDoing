import { chromium } from "playwright-core";
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium", args: ["--no-sandbox"] });
const p = await (await b.newContext({ viewport: { width: 1300, height: 800 } })).newPage();
const errs = []; p.on("pageerror", e => errs.push(e.message));
let fails = 0; const ok = (c, m) => { console.log(c ? "ok  " : "FAIL", m); if (!c) fails++; };
await p.goto("http://localhost:8000/?demo"); await p.waitForSelector("li.item");
await p.locator("li.item .name").first().click({ position: { x: 4, y: 4 } }); await p.waitForSelector(".editor textarea");
const ta = p.locator(".editor textarea"); const val = () => ta.inputValue();
await ta.fill("title\nline a\nline b"); await ta.evaluate(e => e.setSelectionRange(5, 5));
await p.keyboard.press("Tab");
ok(await val() === "title    \nline a\nline b" && await ta.evaluate(e => document.activeElement === e && e.selectionStart === 9), "Tab inserts 4 spaces and keeps focus");
await p.keyboard.press("Control+z"); await ta.evaluate(e => e.setSelectionRange(6, 6)); await p.keyboard.press("Tab"); await p.keyboard.press("Shift+Tab");
ok(await val() === "title\nline a\nline b", "Shift+Tab outdents the current line");
await ta.evaluate(e => e.setSelectionRange(6, e.value.length)); await p.keyboard.press("Tab");
ok(await val() === "title\n    line a\n    line b", "Tab on several lines indents all");
await p.keyboard.press("Shift+Tab");
ok(await val() === "title\nline a\nline b", "Shift+Tab outdents all");
await p.keyboard.press("Control+z"); ok((await val()).includes("    line a"), "undo works");
ok(await p.locator(".hl").first().evaluate(h => h.textContent.includes("    line a")), "highlight layer follows");
ok(errs.length === 0, "no page errors");
await b.close(); process.exit(fails ? 1 : 0);
