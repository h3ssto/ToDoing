import { chromium } from "playwright-core";
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium", args: ["--no-sandbox"] });
const p = await (await b.newContext({ viewport: { width: 1300, height: 800 } })).newPage();
const errs = []; p.on("pageerror", e => errs.push(e.message));
let fails = 0; const ok = (c, m) => { console.log(c ? "ok  " : "FAIL", m); if (!c) fails++; };
await p.goto("http://localhost:8000/?demo"); await p.waitForSelector("li.item");
ok(await p.locator("button.plus").count() >= 3 && await p.locator("form.add button:text-is('Add')").count() === 0, "green plus replaces Add");
const n0 = await p.locator(".col").first().locator("> .board > ul > li.item").count();
const it = p.locator(".col").first().locator("> .board > ul > li.item").first();
await it.hover(); await it.locator(".tools button[title=hide]").click();
await p.waitForFunction(n => document.querySelector(".col").querySelectorAll(":scope > .board > ul > li.item").length === n - 1, n0);
ok(/Show hidden \(1\)/.test(await p.locator(".col").first().locator(".more").textContent()), "item hidden, not deleted");
await p.locator(".col").first().locator(".more").click(); await p.waitForSelector("li.item.hid");
await p.locator("li.item.hid button[title=restore]").click();
await p.waitForFunction(n => document.querySelector(".col").querySelectorAll(":scope > .board > ul > li.item").length === n, n0);
ok(await p.locator("li.item.hid").count() === 0, "restore brings it back");
ok(errs.length === 0, "no page errors " + errs.join(";"));
await p.screenshot({ path: "/tmp/pastel.png" });
await b.close(); process.exit(fails ? 1 : 0);
